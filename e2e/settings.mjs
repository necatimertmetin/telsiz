// Ayarlar: sekmeler, açma-kapama düğmeleri, temalar; masaüstü ve telefon genişliği.
import {chromium} from 'playwright-core'

const URL = process.env.URL ?? 'http://localhost:4173/'
const check = (c, m) => { console.log(c ? 'OK  ' : 'FAIL', m); if (!c) process.exitCode = 1 }
const browser = await chromium.launch({channel: 'chrome', headless: true})
const open = async viewport => {
  const p = await (await browser.newContext({viewport})).newPage()
  p.on('pageerror', e => check(false, 'sayfa hatası: ' + e.message))
  await p.goto(URL)
  await p.getByLabel('Takma adın').fill('Mert')
  await p.getByRole('button', {name: 'Devam'}).click()
  await p.getByLabel('Grup adı').fill('Sinema')
  await p.getByRole('button', {name: 'Kur'}).click()
  if (viewport.width < 768) await p.getByRole('button', {name: 'Menü'}).click()
  await p.getByRole('button', {name: 'Ayarlar', exact: true}).first().click()
  return p
}
const bg = p => p.evaluate(() => getComputedStyle(document.body).backgroundColor)
const noScroll = p => p.evaluate(() => document.documentElement.scrollWidth <= innerWidth)

let p = await open({width: 1300, height: 850})
check(await p.getByRole('tab').count() === 8, 'sekiz sekme var')
check(await p.getByRole('tabpanel', {name: 'Profil'}).isVisible(), 'masaüstünde Profil açık başlıyor')
check(await p.evaluate(() => document.querySelector('.av img')?.src.startsWith('data:image/svg')), 'varsayılan profil resmi canavar')
const face = () => p.evaluate(() => document.querySelector('.profilerow .av img').src)
const f0 = await face()
await p.getByRole('button', {name: 'Zarla, yenisi gelsin'}).click()
check(await face() !== f0, 'zar yeni canavar getirdi')
await p.getByRole('button', {name: 'Rozet', exact: true}).click()
await p.getByRole('button', {name: 'Rozet 3'}).click()
check(await p.evaluate(() => window.telsiz.profiles[window.telsiz.me.uid].look === 'badge' && window.telsiz.profiles[window.telsiz.me.uid].icon === 2), 'rozet ve ikon seçildi')
await p.screenshot({path: 'e2e/out/settings-profile.png'})
await p.getByRole('button', {name: 'Piksel'}).click()
await p.getByRole('button', {name: 'Canavar'}).click()
await p.getByRole('tab', {name: 'Bildirimler'}).click()
const sw = p.getByRole('switch', {name: /Bildirim sesleri/})
const was = await sw.isChecked()
await sw.click()
check(await p.evaluate(() => window.telsiz.prefs.sounds) === !was, 'açma-kapama düğmesi ayarı değiştiriyor')
await sw.click()
await p.getByRole('tab', {name: 'Ses ve görüntü'}).click()
check(await p.getByRole('switch', {name: /Gürültü engelleme/}).isVisible() && await p.getByText(/Ses eşiği/).isVisible(), 'ses sekmesi açılıyor')
await p.getByRole('tab', {name: 'Görünüm'}).click()
const dark = await bg(p)
await p.getByRole('button', {name: 'Gündüz'}).click()
check(await bg(p) !== dark && await p.evaluate(() => document.documentElement.dataset.theme === 'gunduz'), 'Gündüz teması uygulandı')
await p.screenshot({path: 'e2e/out/settings-light.png'})
const fs0 = await p.evaluate(() => document.querySelector('.setnav').getBoundingClientRect().width)
await p.getByRole('button', {name: 'Büyük', exact: true}).click()
check(await p.evaluate(() => document.querySelector('.setnav').getBoundingClientRect().width) > fs0 + 5, 'yazı boyutu büyüdü')
await p.getByRole('group', {name: 'Yazı tipi'}).getByRole('button', {name: /Comic Neue/}).click()
await p.waitForTimeout(800)
check(await p.evaluate(() => getComputedStyle(document.body).fontFamily.includes('Comic Neue')), 'yazı tipi değişti')
check(await p.evaluate(() => Math.abs(document.querySelector('.app, #root > *').getBoundingClientRect().bottom * 1.1 - innerHeight) < 3 || Math.abs(document.querySelector('#root > *').getBoundingClientRect().bottom - innerHeight) < 3), 'büyük yazıda sayfa ekranı dolduruyor')
await p.screenshot({path: 'e2e/out/settings-font.png'})
await p.getByRole('button', {name: 'Normal', exact: true}).click()
await p.getByRole('group', {name: 'Yazı tipi'}).getByRole('button', {name: /Barlow/}).click()
await p.getByRole('button', {name: 'Tonlu desen'}).click()
check(await p.evaluate(() => document.documentElement.dataset.doodle === 'tone' && getComputedStyle(document.querySelector('.chat'), '::before').maskImage.startsWith('url')), 'desenli arka plan açıldı')
await p.getByRole('button', {name: 'Kapat'}).click()
await p.screenshot({path: 'e2e/out/doodle-light.png'})
await p.getByRole('button', {name: 'Ayarlar', exact: true}).first().click()
await p.reload()
check(await p.evaluate(() => document.documentElement.dataset.theme === 'gunduz' && document.documentElement.dataset.doodle === 'tone'), 'tema ve desen yenileyince kalıyor')
await p.getByRole('button', {name: 'Ayarlar', exact: true}).first().click()
await p.getByRole('tab', {name: 'Görünüm'}).click()
await p.getByRole('button', {name: 'Deniz'}).click()
await p.getByRole('button', {name: 'Taktik tonlu'}).click()
check(await p.evaluate(() => document.documentElement.dataset.doodle === 'tac-tone' && getComputedStyle(document.querySelector('.chat'), '::before').maskImage.includes('tac-tone')), 'taktik desen açıldı')
await p.getByRole('button', {name: 'Kapat'}).click()
await p.screenshot({path: 'e2e/out/doodle-deniz.png'})
await p.getByRole('button', {name: 'Ayarlar', exact: true}).first().click()
await p.getByRole('tab', {name: 'Ses ve görüntü'}).click()
await p.screenshot({path: 'e2e/out/settings-desktop.png'})
await p.getByRole('tab', {name: 'Görünüm'}).click()
await p.getByRole('button', {name: 'Gece'}).click()
check(await p.evaluate(() => !document.documentElement.dataset.theme) && await bg(p) === dark, 'Gece temasına dönüyor')
check(await noScroll(p), 'masaüstünde yatay taşma yok')

p = await open({width: 390, height: 800})
check(await p.getByRole('tabpanel').count() === 0 && await p.getByRole('tab', {name: 'Oyun'}).isVisible(), 'telefonda önce liste çıkıyor')
await p.screenshot({path: 'e2e/out/settings-phone-list.png'})
await p.getByRole('tab', {name: 'Oyun'}).click()
check(await p.getByRole('switch', {name: /Oyun modu/}).isVisible() && !(await p.getByRole('tab', {name: 'Profil'}).isVisible()), 'telefonda sekmeye girince sadece o sayfa')
await p.screenshot({path: 'e2e/out/settings-phone-pane.png'})
check(await noScroll(p), 'telefonda yatay taşma yok')
await p.getByRole('button', {name: 'Ayarlar', exact: true}).last().click()
check(await p.getByRole('tab', {name: 'Profil'}).isVisible(), 'geri ile listeye dönüyor')

await browser.close()
console.log(process.exitCode ? 'BAŞARISIZ' : 'TAMAM')
