import {_electron as electron} from 'playwright-core'
import path from 'node:path'
const dir = path.resolve('desktop')
const app = await electron.launch({executablePath: path.join(dir, 'node_modules/electron/dist/electron.exe'), args: [dir], cwd: dir, env: {...process.env, TELSIZ_URL: 'http://localhost:4173/'}})
const w = await app.firstWindow()
w.on('pageerror', e => console.log('ERR', e.message))
await w.waitForLoadState()
await w.waitForFunction(() => window.telsiz)
if (!(await w.evaluate(() => window.telsiz.me.name))) {
  await w.getByLabel('Takma adın').fill('Masaustu')
  await w.getByRole('button', {name: 'Devam'}).click()
}
if (!(await w.evaluate(() => window.telsiz.groups.length))) await w.getByRole('button', {name: 'Kur'}).click()
console.log('bridge', await w.evaluate(() => Object.keys(window.telsizDesktop)))
const src = await w.evaluate(() => window.telsizDesktop.listSources())
console.log('sources', src.length, src.slice(0, 3).map(s => s.name), src[0]?.thumb.length)
console.log('devices', await w.evaluate(async () => (await navigator.mediaDevices.enumerateDevices()).map(d => d.kind + ':' + !!d.label)))
await w.getByRole('button', {name: 'Telsiz odası'}).click()
await w.getByRole('button', {name: 'Sesli katıl'}).last().click()
await w.waitForTimeout(1500)
console.log('voice', await w.evaluate(() => ({inVoice: window.telsiz.session.voice.in, level: window.telsiz.call.level})))
await w.evaluate(id => window.telsizDesktop.pickSource(id, true), src[0].id)
await w.evaluate(() => window.telsiz.call.toggleScreen(true))
await w.waitForTimeout(800)
console.log('screen', await w.evaluate(() => {const st = window.telsiz.call.streams.screen, t = st?.getVideoTracks()[0], a = st?.getAudioTracks()[0]; return [t?.readyState, t?.label, a?.readyState, a?.label]}))
await w.screenshot({path: 'e2e/out/desktop-app.png'})
await app.evaluate(({BrowserWindow}) => { BrowserWindow.getAllWindows()[0].webContents.send('hotkey', 'mute') })
await w.waitForTimeout(300)
console.log('hotkey muted', await w.evaluate(() => window.telsiz.session.voice.muted))
await app.evaluate(({app}) => app.exit(0)).catch(() => {})
process.exit(0)
